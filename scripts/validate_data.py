"""
Run every automated data-quality check and write docs/validation_report.md.

Usage:
    python scripts/validate_data.py          # all checks, incl. regeneration with seed 42 (~10 s)
    python scripts/validate_data.py --fast   # skip the reproducibility check
Exit code is 1 if any check fails.
"""
from __future__ import annotations

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tests"))
import data_quality_checks as dq  # noqa: E402

DESCRIPTIONS = {
    "check_files_match_schema": "Processed CSVs have exactly the columns defined in scripts/schema.py",
    "check_primary_keys_unique": "Primary keys, business keys and target grain are unique",
    "check_no_unexpected_nulls": "No nulls except documented ones (ship date on open orders, first/last order for non-buyers)",
    "check_referential_integrity": "Every fact/target key exists in its dimension; TREATAS values match dimension values",
    "check_order_level_consistency": "Date, customer, channel, geography and status are identical across lines of an order",
    "check_hierarchies_consistent": "Category > Subcategory and Region > State > City hierarchies are clean",
    "check_date_table": "DimDate is contiguous full years 2023-2025 with 1:1 sort-by columns",
    "check_valid_dates": "Ship date >= order date, DaysToShip correct, no future orders",
    "check_financial_reconciliation": "Gross, discount, net sales, cost and profit reconcile on every line (half-cent tolerance)",
    "check_aggregates_reconcile": "Totals by region/category/channel/segment/year equal the grand total; customer enrichment agrees",
    "check_reference_kpis_match_fact": "Reference KPIs (expected Power BI values) recompute from the fact; margin is ratio of sums",
    "check_targets": "Target grid complete, positive, same months as sales, reconciles to the finance workbook",
    "check_cleaning_log": "Raw rows minus removed rows equals fact rows; no test/malformed order IDs remain",
    "check_text_conformed": "No stray whitespace; conformed category, region and channel lists",
    "check_dax_references_exist": "Static lint: every column/measure referenced in DAX exists; balanced parentheses",
    "check_generated_docs_current": "Data dictionary and TMDL script cover every column/measure; theme JSON parses",
    "check_reproducible_generation": "Re-running the generator with seed 42 reproduces the raw files exactly",
}


def main() -> None:
    fast = "--fast" in sys.argv
    results = dq.run_all(skip_slow=fast)
    log = json.loads((ROOT / "data" / "processed" / "cleaning_log.json").read_text())
    passed = sum(ok for _, ok, _ in results)
    lines = [
        "# Validation Report",
        "",
        f"_Generated by `scripts/validate_data.py` on {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC._",
        "",
        f"**Automated checks: {passed}/{len(results)} passed.**" + (" (reproducibility check skipped with --fast)" if fast else ""),
        "",
        "| Check | What it verifies | Result |",
        "|---|---|---|",
    ]
    for name, ok, msg in results:
        lines.append(f"| `{name}` | {DESCRIPTIONS.get(name, '')} | {'PASS' if ok else 'FAIL: ' + msg} |")
    lines += ["", "## Row counts", "", "| Table | Rows |", "|---|---|"]
    lines += [f"| {t} | {n:,} |" for t, n in log["row_counts"].items()]
    lines += ["", "## Cleaning log", "", "| Step | Rows affected | Detail |", "|---|---|---|"]
    lines += [f"| {s['step']} | {s['rows_affected']:,} | {s['detail']} |" for s in log["steps"]]
    lines += ["", "Manual checks that require Power BI Desktop are listed in "
              "[testing_and_validation.md](testing_and_validation.md) - they are **not** covered by this report.", ""]
    (ROOT / "docs" / "validation_report.md").write_text("\n".join(lines), encoding="utf-8")
    for name, ok, msg in results:
        print(f"{'PASS' if ok else 'FAIL'}  {name}" + ("" if ok else f"  -> {msg}"))
    print(f"\n{passed}/{len(results)} checks passed -> docs/validation_report.md")
    sys.exit(0 if passed == len(results) else 1)


if __name__ == "__main__":
    main()
